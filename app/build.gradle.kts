  //  - debug: uses rootDir/debug.keystore only if that file exists, else Android's default debug key
  //  - release: signed only when KEYSTORE_PATH + STORE_PASSWORD + KEY_PASSWORD are set
  val debugKeystore = file("${rootDir}/debug.keystore")
  val releaseKeystorePath = System.getenv("KEYSTORE_PATH")
  val hasReleaseSigning = releaseKeystorePath != null &&
    System.getenv("STORE_PASSWORD") != null &&
    System.getenv("KEY_PASSWORD") != null

  signingConfigs {
    if (hasReleaseSigning) {
      create("release") {
        storeFile = file(releaseKeystorePath!!)
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      }
    }
    if (debugKeystore.exists()) {
      create("debugConfig") {
        storeFile = debugKeystore
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
